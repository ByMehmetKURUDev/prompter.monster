/** Every project file for a state: path → content. */
export function buildProjectFiles(s: StudioState): Record<string, string> {
  const slug =
    s.name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "") || "project";
  return {
    "AGENTS.md": exportAgentsMd(s),
    "CLAUDE.md": exportClaudeMd(s),
    ...exportClaudeAgents(s),
    [`.cursor/rules/${slug}.mdc`]: exportCursorMdc(s),
    ".cursorrules": exportCursorRules(s),
    ".github/copilot-instructions.md": exportCopilotInstructions(s),
    ".taskmaster/docs/prd.txt": exportTaskMasterPrd(s),
    "prompt-monster.json": exportJSON(s),
  };
}
