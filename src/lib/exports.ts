const trimWords = (t: string, n: number) => {
  const w = t.split(/\s+/).filter(Boolean);
  return w.length > n ? `${w.slice(0, n).join(" ")}…` : w.join(" ");
};

function stackLines(s: StudioState): string[] {
  const rows: [string, string[]][] = [
    ["Frontend", s.frontend],
    ["Backend", s.backend],
    ["Database", s.database],
    ["Auth", s.auth],
    ["AI", s.ai],
    ["Infra / realtime", s.realtime],
    ["Search", s.search],
  ];
  return rows.filter(([, v]) => v.length).map(([k, v]) => `- ${k}: ${v.join(", ")}`);
}

function projectLines(s: StudioState, lang: Lang): string[] {
  const w = W[lang];
  const comp = s.competitors.filter(Boolean);
  return [
    `- ${w.what}: ${trimWords(s.description || s.pitch, 80)}`,
    `- ${w.type}: ${projectTypeName(s.projectType)}`,
    s.audience.role ? `- ${w.users}: ${s.audience.role}${s.audience.pain ? ` — ${w.pain}: ${s.audience.pain}` : ""}${s.audience.budget ? ` — ${w.budget}: ${s.audience.budget}` : ""}` : "",
    s.usp ? `- ${w.usp}: ${s.usp}` : "",
    comp.length ? `- ${w.competitors}: ${comp.join(", ")}` : "",
    s.monetization.length ? `- ${w.money}: ${s.monetization.join(", ")}${s.payments.length ? ` · ${w.payments}: ${paymentNames(s.payments)}` : ""}` : "",
    s.compliance.length ? `- ${w.compliance}: ${s.compliance.join(", ")}` : "",
  ].filter(Boolean);
}

/** AGENTS.md — the cross-tool instructions file (agents.md). `title` overrides the heading (Cursor rules reuse the body). */
export function exportAgentsMd(s: StudioState, title = `AGENTS.md — ${s.name}`): string {
  const w = W[s.lang];
  const stack = stackLines(s);
  return [
    `# ${title}`,
    "",
    s.pitch ? `> ${s.pitch}` : "",
    "",
    w.agentsIntro,
    "",
    `## ${w.project}`,
    ...projectLines(s, s.lang),
    "",
    ...(stack.length ? [`## ${w.stack}`, ...stack, ""] : []),
    ...(s.features.length ? [`## ${w.scope}`, ...s.features.map((f, i) => `${i + 1}. ${f}`), ""] : []),
    `## ${w.rules}`,
    ...w.rulesList.map((r) => `- ${r}`),
    "",
    `## ${w.done}`,
    ...w.doneList.map((r) => `- ${r}`),
    "",
    `## ${w.verify}`,
    ...w.verifyList.map((r) => `- [ ] ${r}`),
    "",
    `## ${w.experts}`,
    w.expertsText,
    "",
  ]
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
}

/** .github/copilot-instructions.md — short, self-contained statements (what Copilot follows best). */
export function exportCopilotInstructions(s: StudioState): string {
  const w = W[s.lang];
  return [
    `# ${s.name} — Copilot instructions`,
    "",
    w.copilotIntro,
    "",
    `## ${w.copilotAbout}`,
    s.pitch ? `- ${s.pitch}` : "",
    ...projectLines(s, s.lang),
    "",
    ...(stackLines(s).length ? [`## ${w.stack}`, ...stackLines(s), ""] : []),
    `## ${w.copilotCode}`,
    ...w.rulesList.map((r) => `- ${r}`),
    "",
    `## ${w.verify}`,
    ...w.verifyList.map((r) => `- ${r}`),
    "",
  ]
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
}

/** File-name slug for an expert: "Staff Engineer / CTO" → "staff-engineer-cto". */
export function expertSlug(e: Expert): string {
  return e.role
    .toLowerCase()
    .replace(/&/g, " ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

/** .claude/agents/<expert>.md — one Claude Code subagent per selected expert. */
export function exportClaudeAgents(s: StudioState): Record<string, string> {
  const w = W[s.lang];
  const out: Record<string, string> = {};
  for (const id of s.experts) {
    const e = EXPERTS.find((x) => x.id === id);
    if (!e) continue;
    const task = (s.lang === "EN" ? (e.taskEn ?? e.task) : e.task).replace(/\s+/g, " ").trim();
    const description = w.agentDesc(e, s.name, trimWords(task, 28)).replace(/"/g, "'").replace(/\s+/g, " ");
    out[`.claude/agents/${expertSlug(e)}.md`] = [
      "---",
      `name: ${expertSlug(e)}`,
      `description: "${description}"`,
      "model: inherit",
      "---",
      "",
      w.agentNote,
      "",
      buildExpertPrompt({ ...s, format: "ChatGPT Markdown" }, id),
      "",
    ].join("\n");
  }
  return out;
}

/** .cursor/rules/<slug>.mdc — Cursor's current project-rules format (always applied). */
export function exportCursorMdc(s: StudioState): string {
  const title = s.lang === "TR" ? `${s.name} — proje kuralları` : `${s.name} — project rules`;
  return ["---", `description: ${s.name} — build rules (Prompt.Monster)`, "globs:", "alwaysApply: true", "---", "", exportAgentsMd(s, title)].join("\n");
}

